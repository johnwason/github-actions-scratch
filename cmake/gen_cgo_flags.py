#!/usr/bin/env python3
"""Write the cgo flags file for robotraconteur/internal/swig.

Input: one linker item per line (from CMake). Static archives and plain flags
are passed through; shared library paths (e.g. libboost_thread.so.1.83.0) are
rewritten to -L<dir> -l<name>, the form accepted by cgo's #cgo LDFLAGS
allowlist. <goos> selects the build constraint and the system libraries.

The file also records a fingerprint (size and mtime) of the static archives:
Go's build cache does not track libraries named in #cgo LDFLAGS, so without
it a rebuilt core would not be relinked into Go binaries. The file is only
rewritten when its content changes.

usage: gen_cgo_flags.py <link_libs.txt> <out.go> <goos>
"""
import hashlib
import os
import re
import sys

src, out, goos = sys.argv[1:4]
items = [l.strip() for l in open(src) if l.strip()]
flags = []
for it in items:
    m = re.match(r"^(.*)/lib([^/]+?)\.(so|dylib)(\.[0-9.]+)?$", it)
    if m:
        for f in ("-L" + m.group(1), "-l" + m.group(2)):
            if f not in flags or f.startswith("-l"):
                flags.append(f)
    else:
        flags.append(it)

# Libraries after the group. On Windows (MinGW-w64) libstdc++, libgcc and
# winpthread are linked statically, so Go programs do not need the MinGW
# runtime DLLs on PATH.
SYSTEM_LIBS = {
    "linux": "-lstdc++ -lm -lpthread",
    "windows": "-static -lstdc++ -lwinpthread",
}

fp = hashlib.sha256()
for it in flags:
    if it.endswith(".a") and os.path.exists(it):
        st = os.stat(it)
        fp.update(f"{it}:{st.st_size}:{st.st_mtime_ns}\n".encode())

content = f"""// Code generated by cmake/gen_cgo_flags.py; DO NOT EDIT.

// native libraries fingerprint: {fp.hexdigest()[:32]}

//go:build {goos}

package robotraconteurswig

/*
#cgo LDFLAGS: -Wl,--start-group {' '.join(flags)} -Wl,--end-group {SYSTEM_LIBS.get(goos, SYSTEM_LIBS["linux"])}
*/
import "C"
"""
try:
    with open(out) as f:
        if f.read() == content:
            sys.exit(0)
except OSError:
    pass
with open(out + ".tmp", "w") as f:
    f.write(content)
os.replace(out + ".tmp", out)
