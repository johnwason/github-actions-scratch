package robotraconteur

import (
	"errors"
	"fmt"

	swig "github.com/robotraconteur/robotraconteur_go/robotraconteur/internal/swig"
)

// ErrorCode is a Robot Raconteur error code (MessageErrorType).
type ErrorCode uint32

// String returns the C++ enum name of the code, e.g. "MessageErrorType_ConnectionError".
func (c ErrorCode) String() string {
	if n, ok := errorCodeNames[c]; ok {
		return n
	}
	return fmt.Sprintf("MessageErrorType(%d)", uint32(c))
}

// Error is a Robot Raconteur error. All errors returned by this package for
// failures reported by Robot Raconteur (network, protocol, remote service,
// timeouts, ...) are *Error values, or service defined error types that wrap
// an *Error (generated by RobotRaconteurGenGo).
//
// Use errors.Is with the Err* sentinels to test for a code:
//
//	if errors.Is(err, robotraconteur.ErrRequestTimeout) { ... }
//
// and errors.As to retrieve details:
//
//	var rerr *robotraconteur.Error
//	if errors.As(err, &rerr) { log.Println(rerr.Code, rerr.Name, rerr.Message) }
type Error struct {
	// Code is the error code.
	Code ErrorCode
	// Name is the fully qualified error type name, e.g.
	// "RobotRaconteur.ConnectionError" or "experimental.myservice.MyError".
	Name string
	// Message is the human readable error message.
	Message string
	// SubName is an optional error sub-name.
	SubName string
	// Param is an optional error parameter (a Robot Raconteur varvalue).
	Param any
}

// Error implements the error interface.
func (e *Error) Error() string {
	name := e.Name
	if name == "" {
		name = e.Code.String()
	}
	if e.Message == "" {
		return name
	}
	return name + ": " + e.Message
}

// Is reports whether target is an *Error with the same code. For
// UnknownError and RemoteError, a target with a non-empty Name only matches
// errors with the same Name.
func (e *Error) Is(target error) bool {
	t, ok := target.(*Error)
	if !ok {
		return false
	}
	if t.Code != e.Code {
		return false
	}
	if (t.Code == CodeRemoteError || t.Code == CodeUnknownError) && t.Name != "" {
		return t.Name == e.Name
	}
	return true
}

// errorFromInfo converts a native HandlerErrorInfo into a Go error. Returns
// nil when the info carries no error.
func errorFromInfo(h swig.HandlerErrorInfo) error {
	if h == nil || h.Swigcptr() == 0 {
		return nil
	}
	code := ErrorCode(h.GetError_code())
	if code == CodeNone {
		return nil
	}
	e := &Error{
		Code:    code,
		Name:    h.GetErrorname(),
		Message: h.GetErrormessage(),
		SubName: h.GetErrorsubname(),
	}
	if e.Name == "" {
		e.Name = builtinErrorNames[code]
	}
	// TODO(phase 2): unpack h.GetParam_() into e.Param once varvalue packing exists.
	return downcastError(e)
}

// errorDowncaster converts RemoteError values to service defined error types.
// Set by the service factory registry (generated code registers factories).
var errorDowncaster func(e *Error) error

func downcastError(e *Error) error {
	if e.Code == CodeRemoteError && errorDowncaster != nil {
		if d := errorDowncaster(e); d != nil {
			return d
		}
	}
	return e
}

// AsError converts any error into an *Error for transmission to a remote
// client: *Error (or a wrapper around one) is used as is; any other error
// becomes an UnknownError carrying err.Error().
func AsError(err error) *Error {
	var rerr *Error
	if errors.As(err, &rerr) {
		return rerr
	}
	return &Error{Code: CodeUnknownError, Name: "RobotRaconteur.UnknownError", Message: err.Error()}
}

// newErrorInfo converts err into a native HandlerErrorInfo. The caller must
// delete the result with swig.DeleteHandlerErrorInfo.
func newErrorInfo(err error) swig.HandlerErrorInfo {
	h := swig.NewHandlerErrorInfo()
	if err == nil {
		return h
	}
	e := AsError(err)
	h.SetError_code(uint32(e.Code))
	name := e.Name
	if name == "" {
		name = builtinErrorNames[e.Code]
	}
	h.SetErrorname(name)
	h.SetErrormessage(e.Message)
	h.SetErrorsubname(e.SubName)
	return h
}

// setDirectorError reports err to the C++ side from inside a director
// callback. The DIRECTOR_CALL macros rethrow it as a C++ exception.
func setDirectorError(err error) {
	if err == nil {
		return
	}
	h := newErrorInfo(err)
	defer swig.DeleteHandlerErrorInfo(h)
	swig.Rrgo_director_set_error(h)
}

// recoverDirector must be deferred at the top of every director callback
// that can report errors. A Go panic in user code is converted to an
// UnknownError reported to C++, so panics never unwind through C++ frames.
func recoverDirector() {
	if r := recover(); r != nil {
		setDirectorError(&Error{Code: CodeUnknownError, Name: "RobotRaconteur.UnknownError",
			Message: fmt.Sprintf("panic in Go callback: %v", r)})
	}
}
