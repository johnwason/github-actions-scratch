#!/usr/bin/env python3
"""Write the cgo flags file for robotraconteur/internal/swig.

Input: one linker item per line (from CMake). Static archives and plain flags
are passed through; shared library paths (e.g. libboost_thread.so.1.83.0) are
rewritten to -L<dir> -l<name>, the form accepted by cgo's #cgo LDFLAGS
allowlist.

usage: gen_cgo_flags.py <link_libs.txt> <out.go> <goos>
"""
import os
import re
import sys

src, out, goos = sys.argv[1:4]
items = [l.strip() for l in open(src) if l.strip()]
flags = []
for it in items:
    m = re.match(r"^(.*)/lib([^/]+?)\.(so|dylib)(\.[0-9.]+)?$", it)
    if m:
        for f in ("-L" + m.group(1), "-l" + m.group(2)):
            if f not in flags or f.startswith("-l"):
                flags.append(f)
    else:
        flags.append(it)

with open(out + ".tmp", "w") as f:
    f.write(f"""// Code generated by cmake/gen_cgo_flags.py; DO NOT EDIT.

//go:build {goos}

package robotraconteurswig

/*
#cgo LDFLAGS: -Wl,--start-group {' '.join(flags)} -Wl,--end-group -lstdc++ -lm -lpthread
*/
import "C"
""")
os.replace(out + ".tmp", out)
