// ROS message memory <-> Robot Raconteur structure values (B3).
//
// The Robot Raconteur side is the packed form a structure has on the wire
// (MessageElementNestedElementList of type structure), exactly as code
// generated by RobotRaconteurGen packs the definitions from type_mapper.hpp:
// numbers as arrays (one element for a scalar), strings as char arrays,
// string and message sequences as lists, nested messages as structures.
// Works on both the C++ and the C introspection type supports.

#ifndef VALUE_CONVERTER_HPP_
#define VALUE_CONVERTER_HPP_

#include <RobotRaconteur/Message.h>

#include <stdexcept>
#include <string>

#include "typesupport.hpp"

namespace robotraconteur_ros2_debug_bridge
{

/// A Robot Raconteur value that does not fit the ROS type: wrong element
/// type, a bound or fixed length violated, invalid UTF-8 for a wstring.
/// The message says which field.
class ConversionError : public std::runtime_error
{
public:
  using std::runtime_error::runtime_error;
};

using StructurePtr = RR_INTRUSIVE_PTR<RobotRaconteur::MessageElementNestedElementList>;

/// The Robot Raconteur structure type of a message ("rosmsg_<pkg>__<Name>.<Name>").
std::string message_struct_type(Flavor flavor, const void * members);

/// ROS -> Robot Raconteur. `struct_type` names the top-level structure
/// (for example "rosservice_<pkg>__<Srv>.<Srv>Request"); empty means
/// message_struct_type(). Nested messages are rosmsg_ structures.
StructurePtr ros_to_rr(
  Flavor flavor, const void * members, const void * message,
  const std::string & struct_type = std::string());

/// Robot Raconteur -> ROS, into an initialized message. Fields missing from
/// `value`, and null nested structures, keep the message's values (the
/// defaults, for a fresh message). The structure's type must be
/// `struct_type` (empty: message_struct_type()). Throws ConversionError; the
/// message is then partly written, so discard it.
void rr_to_ros(
  Flavor flavor, const void * members, const StructurePtr & value, void * message,
  const std::string & struct_type = std::string());

}  // namespace robotraconteur_ros2_debug_bridge

#endif  // VALUE_CONVERTER_HPP_
