#!/usr/bin/env python3
"""Generate robotraconteur/errors_gen.go from the upstream core headers.

Reads RR_EXCEPTION_TYPES_INIT (Error.h) - the same list
SWIG/RobotRaconteurSWIGErrorGen.cmake parses for the C#/Java bindings - and the
numeric values of enum MessageErrorType (RobotRaconteurConstants.h) so the
error codes can be Go constants.

usage: gen_go_errors.py <RobotRaconteurCore/include/RobotRaconteur> <out.go>
"""
import os
import re
import sys

inc, out = sys.argv[1:3]
err_h = open(os.path.join(inc, "Error.h")).read().replace("\\\n", " ")
m = re.search(r"#define RR_EXCEPTION_TYPES_INIT\(M,M2\)([^\n]*)", err_h)
entries = re.findall(r"\b(M2?)\(\s*(\w+)\s*,\s*(\w+)\s*(?:,\s*\"([^\"]*)\")?\s*\)", m.group(1))

const_h = open(os.path.join(inc, "RobotRaconteurConstants.h")).read()
body = re.search(r"enum MessageErrorType\s*\{(.*?)\};", const_h, re.S).group(1)
body = re.sub(r"//[^\n]*|/\*.*?\*/", "", body, flags=re.S)
values = {}
v = -1
for item in body.split(","):
    item = item.strip()
    if not item:
        continue
    if "=" in item:
        name, val = [x.strip() for x in item.split("=")]
        v = int(val, 0)
    else:
        name = item
        v += 1
    values[name] = v


def short(code):
    return code[len("MessageErrorType_"):]


lines = ["// Code generated by cmake/gen_go_errors.py from RobotRaconteurCore headers; DO NOT EDIT.",
         "", "package robotraconteur", "", "// Robot Raconteur error codes (MessageErrorType).", "const ("]
for name, val in values.items():
    lines.append(f"\tCode{short(name)} ErrorCode = {val}")
lines += [")", "", "// Sentinel errors for use with errors.Is. Matching is by error code;",
          "// for UnknownError and RemoteError a non-empty sentinel Name must also match.", "var ("]
for kind, cpp, code, name in entries:
    s = short(code)
    lines.append(f"\tErr{s} = &Error{{Code: Code{s}, Name: {name!r}}}".replace("'", '"') if kind == "M"
                 else f"\tErr{s} = &Error{{Code: Code{s}}}")
lines += [")", "", "var builtinErrorNames = map[ErrorCode]string{"]
for kind, cpp, code, name in entries:
    if kind == "M":
        lines.append(f'\tCode{short(code)}: "{name}",')
lines += ["}", ""]
for kind, cpp, code, name in entries:
    s = short(code)
    if kind == "M":
        lines += [f"// New{s} returns a new {name} error.",
                  f"func New{s}(message string) *Error {{",
                  f'\treturn &Error{{Code: Code{s}, Name: "{name}", Message: message}}', "}", ""]
    else:
        lines += [f"// New{s} returns a new {s} error with the given error type name.",
                  f"func New{s}(name, message string) *Error {{",
                  f"\treturn &Error{{Code: Code{s}, Name: name, Message: message}}", "}", ""]
lines += ["// errorCodeNames maps every MessageErrorType value to its C++ enum name.",
          "var errorCodeNames = map[ErrorCode]string{"]
for name, val in values.items():
    lines.append(f'\tCode{short(name)}: "{name}",')
lines += ["}", ""]
tmp = out + ".tmp"
open(tmp, "w").write("\n".join(lines))
os.replace(tmp, out)
